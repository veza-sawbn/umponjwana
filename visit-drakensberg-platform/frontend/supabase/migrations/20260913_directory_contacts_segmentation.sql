-- ============================================================================
-- Visit Drakensberg — Directory Contacts + contact segmentation
--
-- The platform's own outreach address book: establishments compiled from the
-- regional tourism directories (Clarens.co.za, Drakensberg Experience,
-- Drakensberg.org, Midlands Meander) that we want on the platform. These are
-- NOT customers and NOT a supplier's address book:
--   * vd_customer_profiles / vd_customer_segments (20260824) are keyed on
--     auth.users — every one of those rows is a real registered account.
--     A directory establishment has no account, so it can't live there.
--   * vd_supplier_contacts (20260826/27/28) is a *supplier's* list of people
--     who booked with them. A prospect we haven't spoken to yet belongs to
--     no supplier at all.
-- Hence a third contact book, sitting alongside those two under /admin/contacts,
-- with the same shape of segmentation the customer side already has:
-- definitions + computed membership + a recompute function, never hand-assigned.
--
-- Segmentation here is rule-driven rather than hardcoded per segment
-- (vd_recompute_segments' eight fixed queries don't generalise to an
-- open-ended set of source sites and regions): each segment carries a small
-- {"type": …, "value": …} rule, and one query evaluates every rule. Segments
-- for the values actually present in the data (source site, region, sector)
-- are generated by the recompute itself, so importing a list from a new
-- directory site or a new region produces its segment automatically.
--
-- Purely additive: no existing table, function or policy is touched.
-- ============================================================================

-- ────────────────────────────────────────────────────────────────────────────
-- 1. vd_directory_contacts — one row per establishment.
-- ────────────────────────────────────────────────────────────────────────────
create table if not exists vd_directory_contacts (
  id                  uuid primary key default gen_random_uuid(),
  establishment       text not null,
  contact_person      text,
  -- Directory listings routinely publish more than one address/number/site
  -- (a reservations and a general mailbox, a landline and a mobile). The
  -- first is kept as the scalar for lists and exports; the array keeps the
  -- rest so nothing published is thrown away at import time.
  email               text,
  emails              text[] not null default '{}',
  phone               text,
  phones              text[] not null default '{}',
  websites            text[] not null default '{}',
  socials             text[] not null default '{}',
  address             text,
  booking_url         text,
  source_listing_urls text[] not null default '{}',
  -- Segmentation dimensions, split out of the source columns at import.
  source_sites        text[] not null default '{}',
  categories          text[] not null default '{}',
  regions             text[] not null default '{}',
  -- Coarse grouping derived from `categories` (82 distinct raw category
  -- tokens across the four source sites is far too granular to segment on).
  -- An establishment can be in several — a guesthouse with a restaurant is
  -- genuinely both, and should appear in both segments.
  sectors             text[] not null default '{}',
  -- How reachable the listing is, as published: 'Email + phone',
  -- 'Email only', 'Phone only', 'Web/social only', 'No direct contact published'.
  contact_status      text,
  verified_on         date,
  -- Outreach workflow — admin-owned, never overwritten by re-importing the
  -- source list (see vd_directory_contacts_upsert below).
  priority            text check (priority is null or priority in ('high', 'medium', 'low')),
  outreach_status     text not null default 'not_contacted'
                        check (outreach_status in ('not_contacted', 'contacted', 'in_conversation', 'converted', 'declined', 'unreachable')),
  last_contacted      date,
  follow_up_date      date,
  owner               text,
  outreach_notes      text not null default '',
  -- Why a listing has no contact details, carried over from the compile.
  data_notes          text not null default '',
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
-- The establishment name is the identity of a directory row (there is no
-- account, and 40% of the list publishes no email at all), so re-importing
-- an updated compile updates in place instead of duplicating.
create unique index if not exists vd_directory_contacts_name_uidx on vd_directory_contacts (lower(establishment));
create index if not exists vd_directory_contacts_outreach_idx on vd_directory_contacts (outreach_status);
create index if not exists vd_directory_contacts_followup_idx on vd_directory_contacts (follow_up_date) where follow_up_date is not null;

alter table vd_directory_contacts enable row level security;
drop policy if exists "Admins manage directory contacts" on vd_directory_contacts;
create policy "Admins manage directory contacts" on vd_directory_contacts for all using (is_admin());
-- Internal outreach tooling only — no supplier or visitor path reads this
-- table, so unlike most tables in this schema there is no owner-scoped
-- policy alongside the admin one.

-- ────────────────────────────────────────────────────────────────────────────
-- 2. Segments — definitions + computed membership.
-- ────────────────────────────────────────────────────────────────────────────
create table if not exists vd_contact_segments (
  id            text primary key,
  name          text not null,
  description   text not null default '',
  -- UI grouping: 'Reachability' | 'Outreach' | 'Sector' | 'Source' | 'Region'.
  segment_group text not null default 'Other',
  -- {"type": <rule>, "value": <text>} — see vd_apply_contact_segments below
  -- for the supported rule types. A rule type this database doesn't know
  -- matches nothing rather than erroring.
  rule          jsonb not null,
  -- true for the ones the recompute generates from the data itself (source
  -- site / region / sector); false for the seeded, fixed ones. Only
  -- generated segments are retired when their value disappears from the data.
  is_generated  boolean not null default false,
  sort_order    integer not null default 100,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table if not exists vd_contact_segment_members (
  segment_id  text not null references vd_contact_segments(id) on delete cascade,
  contact_id  uuid not null references vd_directory_contacts(id) on delete cascade,
  computed_at timestamptz not null default now(),
  primary key (segment_id, contact_id)
);
create index if not exists vd_contact_segment_members_contact_idx on vd_contact_segment_members (contact_id);

alter table vd_contact_segments enable row level security;
alter table vd_contact_segment_members enable row level security;
drop policy if exists "Admins manage contact segments"     on vd_contact_segments;
drop policy if exists "Admins read contact segment members" on vd_contact_segment_members;
create policy "Admins manage contact segments"      on vd_contact_segments for all using (is_admin());
create policy "Admins read contact segment members" on vd_contact_segment_members for select using (is_admin());
